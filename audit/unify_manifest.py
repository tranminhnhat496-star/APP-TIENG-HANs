#!/usr/bin/env python3
"""Build the unified cleanup manifest (one row per tracked file) from the
two audit CSVs, applying verified corrections. Read-only.
Outputs: audit/manifest-unified.csv + a coverage report on stdout.
"""
import csv
import json
import subprocess
from pathlib import Path

AUDIT = Path('/home/hatch/workspace/v7build/audit')
CLONE = AUDIT / 'clone'

# Corrections verified by the consolidator (hash/grep evidence in
# cleanup-audit.md §"Corrections to the sub-audits"):
# 1. samples/korean-sample.csv: dup-docs said KEEP (runtime link) — wrong.
#    v16.js:776-779 links only korean-sample.xlsx; the CSV has no runtime
#    link. Refs verdict CANDIDATE stands.
# 2. tools/v15lib/test25-run3.log: dup-docs said CANDIDATE as a byte-identical
#    duplicate of test25-run2.log — wrong. sha256 differs (4a07a304... vs
#    60885eae...). It is the only raw record of run 3 -> UNKNOWN.
# 3. tools/v15lib/test25-zip.log: same error (420395b8... != 60885eae...).
#    Only raw record of a ZIP run -> UNKNOWN.
CORRECTIONS = {
    'samples/korean-sample.csv': (
        'CANDIDATE',
        'CORRECTED: no runtime link (v16.js:776-779 links korean-sample.xlsx only); '
        'generated by gen_samples.js:49; mentioned in docs only (CHANGED_FILES.md, '
        'CHANGELOG_V7_to_V8.md, README_V8_IMPORT.md). Refs verdict stands; dup-docs KEEP was wrong.'),
    'tools/v15lib/test25-run3.log': (
        'UNKNOWN',
        'CORRECTED: NOT a duplicate of test25-run2.log (sha256 4a07a304... vs 60885eae...); '
        'only raw record of test25 run 3; no doc reference. Was CANDIDATE on a false duplicate claim.'),
    'tools/v15lib/test25-zip.log': (
        'UNKNOWN',
        'CORRECTED: NOT a duplicate of test25-run2.log (sha256 420395b8... vs 60885eae...); '
        'only raw record of a test25 ZIP run; no doc reference. Was CANDIDATE on a false duplicate claim.'),
}


def read_csv(path):
    with open(path, newline='', encoding='utf-8') as f:
        r = csv.DictReader(f)
        rows = {}
        for row in r:
            rows[row['path']] = row
        return rows


def main():
    refs = read_csv(AUDIT / 'manifest.csv')
    dups = read_csv(AUDIT / 'dup-docs.csv')
    print(f'refs rows: {len(refs)}; dup-docs rows: {len(dups)}')
    overlap = sorted(set(refs) & set(dups))
    print(f'overlap ({len(overlap)}): {overlap}')
    for p in overlap:
        v1, v2 = refs[p]['verdict'], dups[p]['verdict']
        if v1 != v2:
            print(f'  VERDICT CONFLICT {p}: refs={v1} dup-docs={v2}')

    tracked = subprocess.check_output(
        ['git', '-C', str(CLONE), 'ls-files'], text=True).splitlines()
    print(f'tracked files: {len(tracked)}')

    unified = {}
    for p, row in refs.items():
        unified[p] = dict(row, source='refs')
    for p, row in dups.items():
        if p in unified:
            # keep refs row (runtime evidence is primary); note the second source
            unified[p]['source'] = 'refs+dup-docs'
        else:
            unified[p] = dict(row, source='dup-docs')

    missing = [p for p in tracked if p not in unified]
    extra = [p for p in unified if p not in tracked]
    print(f'unified rows: {len(unified)}; missing from manifests: {missing}; extra: {extra}')

    for p, (verdict, evidence) in CORRECTIONS.items():
        old = unified[p]['verdict']
        unified[p]['verdict'] = verdict
        unified[p]['evidence'] = evidence
        unified[p]['source'] += '+corrected'
        print(f'corrected {p}: {old} -> {verdict}')

    # totals
    from collections import Counter
    cnt = Counter(r['verdict'] for r in unified.values())
    byt = {}
    for r in unified.values():
        byt[r['verdict']] = byt.get(r['verdict'], 0) + int(r['size_bytes'])
    print('verdict totals:', dict(cnt))
    print('bytes totals:', byt)
    print('total bytes:', sum(byt.values()))

    out = AUDIT / 'manifest-unified.csv'
    with open(out, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['path', 'size_bytes', 'sha256', 'verdict', 'evidence', 'source'])
        for p in sorted(unified):
            r = unified[p]
            w.writerow([p, r['size_bytes'], r['sha256'], r['verdict'], r['evidence'], r['source']])
    print(f'wrote {out} ({len(unified)} rows)')


if __name__ == '__main__':
    main()
